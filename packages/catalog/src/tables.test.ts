import { describe, expect, test } from "vitest";

import { loadCatalog } from "./index.ts";
import { table } from "./test-helpers.ts";

describe("tables", () => {
  test("lists user tables in schema then name order, without system tables", async () => {
    const catalog = await loadCatalog(`
      create schema app;
      create table public.b (id int);
      create table app.z (id int);
      create table public.a (id int);
    `);
    expect(catalog.tables.map((entry) => `${entry.schema}.${entry.name}`)).toStrictEqual([
      "app.z",
      "public.a",
      "public.b",
    ]);
  });

  test("reads columns in definition order with their type and nullability", async () => {
    const catalog = await loadCatalog(`
      create table users (
        id int8 not null,
        name varchar(20),
        tags text[] not null,
        balance numeric(10, 2)
      );
    `);
    expect(table(catalog, "users").columns).toStrictEqual([
      expect.objectContaining({
        name: "id",
        type: { kind: "base", schema: "pg_catalog", name: "int8" },
        typeSql: "bigint",
        notNull: true,
      }),
      expect.objectContaining({
        name: "name",
        type: { kind: "base", schema: "pg_catalog", name: "varchar" },
        typeSql: "character varying(20)",
        notNull: false,
      }),
      expect.objectContaining({
        name: "tags",
        type: { kind: "array", element: { kind: "base", schema: "pg_catalog", name: "text" } },
        typeSql: "text[]",
        notNull: true,
      }),
      expect.objectContaining({
        name: "balance",
        type: { kind: "base", schema: "pg_catalog", name: "numeric" },
        typeSql: "numeric(10,2)",
        notNull: false,
      }),
    ]);
  });

  test.each([
    { definition: "a int", value: { kind: "none" } },
    { definition: "a int default 42", value: { kind: "default", expression: "42" } },
    { definition: "a timestamptz default now()", value: { kind: "default", expression: "now()" } },
    {
      definition: "a int generated always as identity",
      value: { kind: "identity", generation: "always" },
    },
    {
      definition: "a int generated by default as identity",
      value: { kind: "identity", generation: "by default" },
    },
    {
      definition: "a int generated always as (b * 2) stored",
      value: { kind: "generated", storage: "stored", expression: "(b * 2)" },
    },
    {
      definition: "a int generated always as (b * 2) virtual",
      value: { kind: "generated", storage: "virtual", expression: "(b * 2)" },
    },
  ])("reads how $definition gets its value", async ({ definition, value }) => {
    const catalog = await loadCatalog(`create table t (b int, ${definition});`);
    const column = table(catalog, "t").columns.find((candidate) => candidate.name === "a");
    expect(column?.value).toStrictEqual(value);
  });
});
