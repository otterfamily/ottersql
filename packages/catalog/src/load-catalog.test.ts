import { describe, expect, test } from "vitest";
import { loadCatalog, type Catalog, type Table } from "./index.ts";

function table(catalog: Catalog, name: string, schema = "public"): Table {
  const found = catalog.tables.find((t) => t.schema === schema && t.name === name);
  if (found === undefined) throw new Error(`table ${schema}.${name} not in catalog`);
  return found;
}

describe("tables", () => {
  test("lists user tables in schema then name order, without system tables", async () => {
    const catalog = await loadCatalog(`
      create schema app;
      create table public.b (id int);
      create table app.z (id int);
      create table public.a (id int);
    `);
    expect(catalog.tables.map((t) => `${t.schema}.${t.name}`)).toEqual([
      "app.z",
      "public.a",
      "public.b",
    ]);
  });

  test("reads columns in definition order with their type and nullability", async () => {
    const catalog = await loadCatalog(`
      create table users (
        id int8 not null,
        name varchar(20),
        tags text[] not null,
        balance numeric(10, 2)
      );
    `);
    expect(table(catalog, "users").columns).toEqual([
      expect.objectContaining({
        name: "id",
        type: { kind: "base", schema: "pg_catalog", name: "int8" },
        typeSql: "bigint",
        notNull: true,
      }),
      expect.objectContaining({
        name: "name",
        type: { kind: "base", schema: "pg_catalog", name: "varchar" },
        typeSql: "character varying(20)",
        notNull: false,
      }),
      expect.objectContaining({
        name: "tags",
        type: { kind: "array", element: { kind: "base", schema: "pg_catalog", name: "text" } },
        typeSql: "text[]",
        notNull: true,
      }),
      expect.objectContaining({
        name: "balance",
        type: { kind: "base", schema: "pg_catalog", name: "numeric" },
        typeSql: "numeric(10,2)",
        notNull: false,
      }),
    ]);
  });

  test.each([
    { definition: "a int", value: { kind: "none" } },
    { definition: "a int default 42", value: { kind: "default", expression: "42" } },
    { definition: "a timestamptz default now()", value: { kind: "default", expression: "now()" } },
    {
      definition: "a int generated always as identity",
      value: { kind: "identity", generation: "always" },
    },
    {
      definition: "a int generated by default as identity",
      value: { kind: "identity", generation: "by default" },
    },
    {
      definition: "a int generated always as (b * 2) stored",
      value: { kind: "generated", storage: "stored", expression: "(b * 2)" },
    },
    {
      definition: "a int generated always as (b * 2) virtual",
      value: { kind: "generated", storage: "virtual", expression: "(b * 2)" },
    },
  ])("reads how $definition gets its value", async ({ definition, value }) => {
    const catalog = await loadCatalog(`create table t (b int, ${definition});`);
    const column = table(catalog, "t").columns.find((c) => c.name === "a");
    expect(column?.value).toEqual(value);
  });
});

describe("keys", () => {
  test("reads a composite primary key in key order", async () => {
    const catalog = await loadCatalog(`create table t (a int, b int, primary key (b, a));`);
    expect(table(catalog, "t").primaryKey).toEqual({ name: "t_pkey", columns: ["b", "a"] });
  });

  test("has no primary key when the table declares none", async () => {
    const catalog = await loadCatalog(`create table t (a int);`);
    expect(table(catalog, "t").primaryKey).toBeNull();
  });

  test("reads unique constraints with their columns, null handling and deferral", async () => {
    const catalog = await loadCatalog(`
      create table t (
        a int, b int, c int,
        constraint t_b_a_key unique (b, a),
        constraint t_c_key unique nulls not distinct (c) deferrable initially deferred
      );
    `);
    expect(table(catalog, "t").uniqueConstraints).toEqual([
      {
        name: "t_b_a_key",
        columns: ["b", "a"],
        nullsNotDistinct: false,
        deferral: "not deferrable",
      },
      { name: "t_c_key", columns: ["c"], nullsNotDistinct: true, deferral: "initially deferred" },
    ]);
  });

  test("reads composite foreign keys with their actions, match type and state", async () => {
    const catalog = await loadCatalog(`
      create schema app;
      create table app.parent (x int, y int, primary key (x, y));
      create table child (
        px int, py int,
        constraint child_parent_fkey foreign key (px, py) references app.parent (x, y)
          match full on update cascade on delete set null deferrable,
        constraint child_loose_fkey foreign key (px, py) references app.parent (x, y) not enforced
      );
      alter table child add constraint child_lazy_fkey
        foreign key (px, py) references app.parent (x, y) not valid;
    `);
    expect(table(catalog, "child").foreignKeys).toEqual([
      {
        name: "child_lazy_fkey",
        columns: ["px", "py"],
        references: { schema: "app", table: "parent", columns: ["x", "y"] },
        match: "simple",
        onUpdate: "no action",
        onDelete: "no action",
        deferral: "not deferrable",
        enforcement: "not valid",
      },
      {
        name: "child_loose_fkey",
        columns: ["px", "py"],
        references: { schema: "app", table: "parent", columns: ["x", "y"] },
        match: "simple",
        onUpdate: "no action",
        onDelete: "no action",
        deferral: "not deferrable",
        enforcement: "not enforced",
      },
      {
        name: "child_parent_fkey",
        columns: ["px", "py"],
        references: { schema: "app", table: "parent", columns: ["x", "y"] },
        match: "full",
        onUpdate: "cascade",
        onDelete: "set null",
        deferral: "initially immediate",
        enforcement: "validated",
      },
    ]);
  });
});

describe("check constraints", () => {
  test("reads the expression, columns and enforcement of a check", async () => {
    const catalog = await loadCatalog(`
      create table t (a int, b int, constraint t_order check (a < b));
      alter table t add constraint t_positive check (a > 0) not valid;
    `);
    expect(table(catalog, "t").checks).toEqual([
      {
        name: "t_order",
        expression: "(a < b)",
        columns: ["a", "b"],
        allowedValues: null,
        enforcement: "validated",
      },
      {
        name: "t_positive",
        expression: "(a > 0)",
        columns: ["a"],
        allowedValues: null,
        enforcement: "not valid",
      },
    ]);
  });

  test.each([
    { column: "a text check (a in ('x', 'it''s'))", allowed: ["x", "it's"] },
    { column: "a varchar(10) check (a in ('x', 'y'))", allowed: ["x", "y"] },
    { column: "a text check (a in ('only'))", allowed: ["only"] },
    { column: "a text check (a in ('x, ''y', 'z'))", allowed: ["x, 'y", "z"] },
    { column: `"A b" text check ("A b" in ('x'))`, allowed: ["x"] },
    { column: "a int check (a in (1, 2))", allowed: null },
    { column: "a text check (a is not null and a in ('x'))", allowed: null },
    { column: "a text check (length(a) < 5)", allowed: null },
  ])("reads $allowed as the values allowed by $column", async ({ column, allowed }) => {
    const catalog = await loadCatalog(`create table t (${column});`);
    const [check] = table(catalog, "t").checks;
    expect(check?.allowedValues).toEqual(
      allowed === null ? null : { column: check?.columns[0], values: allowed },
    );
  });
});
