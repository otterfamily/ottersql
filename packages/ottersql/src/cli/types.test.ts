import { readFile, rm } from "node:fs/promises";
import { join } from "node:path";

import { describe, expect, test } from "vitest";

import { at, ottersql, ottersqlJson, project, writeFiles } from "./test-cli.ts";

const files = {
  "db/schema.sql": "create table users (id int8 primary key, email text not null);\n",
  "db/migrations/20261025000000_init.sql": "-- ottersql:step kind=custom object=users\nselect 1;\n",
  "src/users.sql": "-- @name userById\nselect id, email from users where id = :id;\n",
  "node_modules/some-package/queries.sql": "not a query file of the project\n",
};

describe("ottersql types", () => {
  test("writes declarations next to each query file, leaving out schema.sql, migrations and dependencies", async () => {
    const root = await project(files);
    const written = await ottersqlJson(root, ["types"]);
    const declarations = await readFile(join(root, "src/users.d.sql.ts"), "utf8");
    expect({
      written,
      declarations: [declarations.split("\n")[0], declarations.includes("const userById")],
      again: at(await ottersqlJson(root, ["types"]), "json", "result", "written"),
    }).toStrictEqual({
      written: {
        exitCode: 0,
        json: {
          ok: true,
          command: "types",
          result: { written: ["src/users.d.sql.ts"], removed: [], problems: [] },
        },
      },
      declarations: ["// Generated by ottersql from users.sql. Do not edit.", true],
      again: [],
    });
  });

  test("with --check, reports missing and out-of-date files and writes nothing", async () => {
    const root = await project(files);
    const missing = await ottersqlJson(root, ["types", "--check"]);
    await ottersqlJson(root, ["types"]);
    const upToDate = await ottersqlJson(root, ["types", "--check"]);
    await writeFiles(root, {
      "src/users.sql": "-- @name userCount\nselect count(*) from users;\n",
    });
    expect({
      missing: [missing.exitCode, at(missing.json, "code"), at(missing.json, "result", "written")],
      upToDate: upToDate.exitCode,
      changed: at(await ottersqlJson(root, ["types", "--check"]), "json", "result", "written"),
    }).toStrictEqual({
      missing: [4, "types.out_of_date", ["src/users.d.sql.ts"]],
      upToDate: 0,
      changed: ["src/users.d.sql.ts"],
    });
  });

  test("removes the declarations it wrote for a query file that is gone", async () => {
    const root = await project(files);
    await writeFiles(root, { "src/old.sql": "-- @name one\nselect 1 as one;\n" });
    await ottersqlJson(root, ["types"]);
    await rm(join(root, "src/old.sql"));
    const result = await ottersqlJson(root, ["types"]);
    expect({
      removed: at(result.json, "result", "removed"),
      left: await readFile(join(root, "src/old.d.sql.ts"), "utf8").catch(() => null),
    }).toStrictEqual({ removed: ["src/old.d.sql.ts"], left: null });
  });

  test("refuses to replace a declaration file a person wrote", async () => {
    const root = await project({ ...files, "src/users.d.sql.ts": "export {};\n" });
    const { exitCode, json } = await ottersqlJson(root, ["types"]);
    expect({ exitCode, code: at(json, "code"), where: at(json, "where") }).toStrictEqual({
      exitCode: 2,
      code: "types.not_generated",
      where: { file: "src/users.d.sql.ts" },
    });
  });

  test("still writes the file of a query Postgres rejects, and names where the query is wrong", async () => {
    const root = await project({
      ...files,
      "src/users.sql": "-- @name broken\nselect missing from users;\n",
    });
    const { exitCode, json } = await ottersqlJson(root, ["types"]);
    expect({
      exitCode,
      code: at(json, "code"),
      where: at(json, "where"),
      written: at(json, "result", "written"),
    }).toStrictEqual({
      exitCode: 4,
      code: "types.query_invalid",
      where: { file: "src/users.sql", line: 2 },
      written: ["src/users.d.sql.ts"],
    });
  });

  test("with --check, reports a query Postgres rejects even when the files are up to date", async () => {
    const root = await project({
      ...files,
      "src/users.sql": "-- @name broken\nselect missing from users;\n",
    });
    await ottersql(root, ["types"]);
    const { exitCode, json } = await ottersqlJson(root, ["types", "--check"]);
    expect({ exitCode, code: at(json, "code") }).toStrictEqual({
      exitCode: 4,
      code: "types.query_invalid",
    });
  });

  test("leaves out .sql files of other tools, which have no -- @name line, and the tsconfig's outDir and exclude", async () => {
    const root = await project({
      ...files,
      "supabase/migrations/001_init.sql": "create table notes (id int8);\n",
      "supabase/seed.sql": "insert into notes values (1);\n",
      "dist/users.sql": files["src/users.sql"],
      "fixtures/users.sql": files["src/users.sql"],
      "tsconfig.json": JSON.stringify({
        compilerOptions: { outDir: "dist" },
        exclude: ["fixtures"],
        contentMappers: [
          { package: "ottersql", extensions: [".sql"], options: { schema: "db/schema.sql" } },
        ],
      }),
    });
    const { exitCode, json } = await ottersqlJson(root, ["types"]);
    expect({ exitCode, written: at(json, "result", "written") }).toStrictEqual({
      exitCode: 0,
      written: ["src/users.d.sql.ts"],
    });
  });

  test("reads the schema option through extends, relative to the tsconfig that sets it", async () => {
    const root = await project({
      "sql/schema.sql": files["db/schema.sql"],
      "src/users.sql": files["src/users.sql"],
      "configs/base.json": JSON.stringify({
        contentMappers: [
          { package: "ottersql", extensions: [".sql"], options: { schema: "../sql/schema.sql" } },
        ],
      }),
      "tsconfig.json": JSON.stringify({ extends: "./configs/base.json" }),
    });
    const { exitCode, json } = await ottersqlJson(root, ["types", "--check"]);
    expect({ exitCode, written: at(json, "result", "written") }).toStrictEqual({
      exitCode: 4,
      written: ["src/users.d.sql.ts"],
    });
  });

  test(`reads \${configDir} in an extended outDir and exclude as the directory of the tsconfig it starts from`, async () => {
    const root = await project({
      ...files,
      "dist/users.sql": files["src/users.sql"],
      "fixtures/users.sql": files["src/users.sql"],
      "configs/base.json": JSON.stringify({
        compilerOptions: { outDir: `\${configDir}/dist` },
        exclude: [`\${configDir}/fixtures`],
      }),
      "tsconfig.json": JSON.stringify({ extends: "./configs/base.json" }),
    });
    const { exitCode, json } = await ottersqlJson(root, ["types"]);
    expect({ exitCode, written: at(json, "result", "written") }).toStrictEqual({
      exitCode: 0,
      written: ["src/users.d.sql.ts"],
    });
  });

  test("is the only command that takes --check", async () => {
    const root = await project(files);
    const { exitCode, json } = await ottersqlJson(root, ["migrate", "check", "--check"]);
    expect({ exitCode, code: at(json, "code") }).toStrictEqual({
      exitCode: 2,
      code: "usage.invalid",
    });
  });
});
