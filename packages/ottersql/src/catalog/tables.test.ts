import { describe, expect, test } from "vitest";

import { loadCatalog } from "./index.ts";
import { table } from "./test-helpers.ts";

describe("ottersql's own schema", () => {
  test("is left out, so a migration never plans to drop the record of applied steps", async () => {
    const catalog = await loadCatalog(`
      create schema ottersql;
      create table ottersql.applied_steps (plan text);
      create table users (id int8);
    `);
    expect(catalog.tables.map(({ schema, name }) => `${schema}.${name}`)).toStrictEqual([
      "public.users",
    ]);
  });
});

describe("tables", () => {
  test("starts every load from an empty database", async () => {
    await loadCatalog(`create table left_behind (a int);`);
    const catalog = await loadCatalog(`create table fresh (a int);`);
    expect(catalog.tables.map((entry) => entry.name)).toStrictEqual(["fresh"]);
  });

  test("lists user tables in schema then name order, without system tables", async () => {
    const catalog = await loadCatalog(`
      create schema app;
      create table public.b (id int);
      create table app.z (id int);
      create table public.a (id int);
    `);
    expect(catalog.tables.map((entry) => `${entry.schema}.${entry.name}`)).toStrictEqual([
      "app.z",
      "public.a",
      "public.b",
    ]);
  });

  test("reads columns in definition order with their type and nullability", async () => {
    const catalog = await loadCatalog(`
      create table users (
        id int8 not null,
        name varchar(20),
        tags text[] not null,
        balance numeric(10, 2)
      );
    `);
    expect(table(catalog, "users").columns).toStrictEqual([
      expect.objectContaining({
        name: "id",
        type: { kind: "base", schema: "pg_catalog", name: "int8" },
        typeSql: "bigint",
        notNull: true,
      }),
      expect.objectContaining({
        name: "name",
        type: { kind: "base", schema: "pg_catalog", name: "varchar" },
        typeSql: "character varying(20)",
        notNull: false,
      }),
      expect.objectContaining({
        name: "tags",
        type: { kind: "array", element: { kind: "base", schema: "pg_catalog", name: "text" } },
        typeSql: "text[]",
        notNull: true,
      }),
      expect.objectContaining({
        name: "balance",
        type: { kind: "base", schema: "pg_catalog", name: "numeric" },
        typeSql: "numeric(10,2)",
        notNull: false,
      }),
    ]);
  });

  test.each([
    { definition: "a int", value: { kind: "none" } },
    {
      definition: "a int default 42",
      value: { kind: "default", expression: "42", volatile: false },
    },
    {
      definition: "a timestamptz default now()",
      value: { kind: "default", expression: "now()", volatile: false },
    },
    {
      definition: "a uuid default gen_random_uuid()",
      value: { kind: "default", expression: "gen_random_uuid()", volatile: true },
    },
    {
      definition: "a uuid default my_uuid7()",
      value: { kind: "default", expression: "my_uuid7()", volatile: true },
    },
    {
      definition: "a int default b_plus_one(1) + 1",
      value: { kind: "default", expression: "(b_plus_one(1) + 1)", volatile: false },
    },
    {
      definition: "a serial",
      value: {
        kind: "default",
        expression: "nextval('t_a_seq'::regclass)",
        volatile: true,
      },
    },
    {
      definition: "a int generated always as identity",
      value: { kind: "identity", generation: "always" },
    },
    {
      definition: "a int generated by default as identity",
      value: { kind: "identity", generation: "by default" },
    },
    {
      definition: "a int generated always as (b * 2) stored",
      value: { kind: "generated", storage: "stored", expression: "(b * 2)" },
    },
    {
      definition: "a int generated always as (b * 2) virtual",
      value: { kind: "generated", storage: "virtual", expression: "(b * 2)" },
    },
  ])(
    "reads how $definition gets its value, and whether a default is volatile",
    async ({ definition, value }) => {
      const catalog = await loadCatalog(`
      create function my_uuid7() returns uuid language sql volatile as 'select gen_random_uuid()';
      create function b_plus_one(int) returns int language sql immutable as 'select $1 + 1';
      create table t (b int, ${definition});
    `);
      const column = table(catalog, "t").columns.find((candidate) => candidate.name === "a");
      expect(column?.value).toStrictEqual(value);
    },
  );

  test("treats a column as nullable while its not-null constraint is not valid", async () => {
    const catalog = await loadCatalog(`
      create table t (a int, b int not null);
      alter table t add constraint t_a_not_null not null a not valid;
    `);
    expect(
      table(catalog, "t").columns.map(({ name, notNull }) => ({ name, notNull })),
    ).toStrictEqual([
      { name: "a", notNull: false },
      { name: "b", notNull: true },
    ]);
  });
});
