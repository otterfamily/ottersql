import { describe, expect, test } from "vitest";

import { findTable } from "./find.ts";
import { loadCatalog } from "./index.ts";
import { table } from "./test-helpers.ts";

describe("schemas left out", () => {
  test.for([
    { options: {}, tables: ["audit.events", "ottersql.applied_steps", "public.users"] },
    { options: { omitSchemas: ["ottersql"] }, tables: ["audit.events", "public.users"] },
    { options: { omitSchemas: ["ottersql", "audit"] }, tables: ["public.users"] },
  ])(
    "reads every user schema but those it is told to omit: $options",
    async ({ options, tables }) => {
      const catalog = await loadCatalog(
        `
        create schema ottersql;
        create table ottersql.applied_steps (plan text);
        create schema audit;
        create table audit.events (id int8);
        create table users (id int8);
      `,
        options,
      );
      expect(catalog.tables.map(({ schema, name }) => `${schema}.${name}`)).toStrictEqual(tables);
    },
  );
});

describe("tables", () => {
  test("starts every load from an empty database", async () => {
    await loadCatalog(`create table left_behind (a int);`);
    const catalog = await loadCatalog(`create table fresh (a int);`);
    expect(catalog.tables.map((entry) => entry.name)).toStrictEqual(["fresh"]);
  });

  test("lists user tables in schema then name order, without system tables", async () => {
    const catalog = await loadCatalog(`
      create schema app;
      create table public.b (id int);
      create table app.z (id int);
      create table public.a (id int);
    `);
    expect(catalog.tables.map((entry) => `${entry.schema}.${entry.name}`)).toStrictEqual([
      "app.z",
      "public.a",
      "public.b",
    ]);
  });

  test("reads columns in definition order with their type and nullability", async () => {
    const catalog = await loadCatalog(`
      create table users (
        id int8 not null,
        name varchar(20),
        tags text[] not null,
        balance numeric(10, 2)
      );
    `);
    expect(table(catalog, "users").columns).toStrictEqual([
      expect.objectContaining({
        name: "id",
        type: { kind: "base", schema: "pg_catalog", name: "int8" },
        typeSql: "bigint",
        notNull: true,
      }),
      expect.objectContaining({
        name: "name",
        type: { kind: "base", schema: "pg_catalog", name: "varchar" },
        typeSql: "character varying(20)",
        notNull: false,
      }),
      expect.objectContaining({
        name: "tags",
        type: { kind: "array", element: { kind: "base", schema: "pg_catalog", name: "text" } },
        typeSql: "text[]",
        notNull: true,
      }),
      expect.objectContaining({
        name: "balance",
        type: { kind: "base", schema: "pg_catalog", name: "numeric" },
        typeSql: "numeric(10,2)",
        notNull: false,
      }),
    ]);
  });

  test.each([
    { definition: "a int", value: { kind: "none" } },
    {
      definition: "a int default 42",
      value: { kind: "default", expression: "42", volatile: false },
    },
    {
      definition: "a timestamptz default now()",
      value: { kind: "default", expression: "now()", volatile: false },
    },
    {
      definition: "a uuid default gen_random_uuid()",
      value: { kind: "default", expression: "gen_random_uuid()", volatile: true },
    },
    {
      definition: "a uuid default my_uuid7()",
      value: { kind: "default", expression: "my_uuid7()", volatile: true },
    },
    {
      definition: "a int default b_plus_one(1) + 1",
      value: { kind: "default", expression: "(b_plus_one(1) + 1)", volatile: false },
    },
    {
      definition: "a int generated always as identity",
      value: {
        kind: "identity",
        generation: "always",
        sequence: {
          schema: "public",
          name: "t_a_seq",
          dataType: "integer",
          start: "1",
          increment: "1",
          minimum: "1",
          maximum: "2147483647",
          cache: "1",
          cycle: false,
        },
      },
    },
    {
      definition: "a int generated by default as identity",
      value: {
        kind: "identity",
        generation: "by default",
        sequence: {
          schema: "public",
          name: "t_a_seq",
          dataType: "integer",
          start: "1",
          increment: "1",
          minimum: "1",
          maximum: "2147483647",
          cache: "1",
          cycle: false,
        },
      },
    },
    {
      definition: "a int generated always as identity (start with 100 increment by 5)",
      value: {
        kind: "identity",
        generation: "always",
        sequence: {
          schema: "public",
          name: "t_a_seq",
          dataType: "integer",
          start: "100",
          increment: "5",
          minimum: "1",
          maximum: "2147483647",
          cache: "1",
          cycle: false,
        },
      },
    },
    {
      definition: "a serial",
      value: {
        kind: "sequence",
        sequence: {
          schema: "public",
          name: "t_a_seq",
          dataType: "integer",
          start: "1",
          increment: "1",
          minimum: "1",
          maximum: "2147483647",
          cache: "1",
          cycle: false,
        },
      },
    },
    {
      definition: "a int8 default nextval('tickets')",
      value: { kind: "default", expression: "nextval('tickets'::regclass)", volatile: true },
    },
    {
      definition: "a int generated always as (b * 2) stored",
      value: { kind: "generated", storage: "stored", expression: "(b * 2)" },
    },
    {
      definition: "a int generated always as (b * 2) virtual",
      value: { kind: "generated", storage: "virtual", expression: "(b * 2)" },
    },
  ])(
    "reads how $definition gets its value, and whether a default is volatile",
    async ({ definition, value }) => {
      const catalog = await loadCatalog(`
      create function my_uuid7() returns uuid language sql volatile as 'select gen_random_uuid()';
      create function b_plus_one(int) returns int language sql immutable as 'select $1 + 1';
      create sequence tickets;
      create table t (b int, ${definition});
    `);
      const column = table(catalog, "t").columns.find((candidate) => candidate.name === "a");
      expect(column?.value).toStrictEqual(value);
    },
  );

  test("treats a column as nullable while its not-null constraint is not valid", async () => {
    const catalog = await loadCatalog(`
      create table t (a int, b int not null);
      alter table t add constraint t_a_not_null not null a not valid;
    `);
    expect(
      table(catalog, "t").columns.map(({ name, notNull }) => ({ name, notNull })),
    ).toStrictEqual([
      { name: "a", notNull: false },
      { name: "b", notNull: true },
    ]);
  });
});

describe("inheritance and triggers", () => {
  test("reads which NOT NULL and check constraints do not reach inheriting tables", async () => {
    const catalog = await loadCatalog(`
      create table parent (
        own text not null no inherit,
        shared text not null,
        checked text check (checked is not null) no inherit
      );
    `);
    const parent = table(catalog, "parent");
    expect(
      parent.columns.map(({ name, notNull, notNullNoInherit }) => ({
        name,
        notNull,
        notNullNoInherit,
      })),
    ).toStrictEqual([
      { name: "own", notNull: true, notNullNoInherit: true },
      { name: "shared", notNull: true, notNullNoInherit: false },
      { name: "checked", notNull: false, notNullNoInherit: false },
    ]);
    expect(parent.checks.map(({ noInherit }) => noInherit)).toStrictEqual([true]);
  });

  test("reads the triggers a schema declares, with their timing, events, level and definition", async () => {
    const catalog = await loadCatalog(`
      create table t (id int8 primary key, parent int8 references t);
      create function touch() returns trigger language plpgsql as 'begin return new; end';
      create trigger a_fill before insert or update on t for each row execute function touch();
      create trigger b_audit after delete or truncate on t execute function touch();
    `);
    expect(table(catalog, "t").triggers).toStrictEqual([
      {
        name: "a_fill",
        timing: "before",
        events: ["insert", "update"],
        forEachRow: true,
        definition:
          "CREATE TRIGGER a_fill BEFORE INSERT OR UPDATE ON public.t FOR EACH ROW EXECUTE FUNCTION touch()",
      },
      {
        name: "b_audit",
        timing: "after",
        events: ["delete", "truncate"],
        forEachRow: false,
        definition:
          "CREATE TRIGGER b_audit AFTER DELETE OR TRUNCATE ON public.t FOR EACH STATEMENT EXECUTE FUNCTION touch()",
      },
    ]);
  });
});

describe("finding a table by name", () => {
  test("tells apart names whose text runs across the dot between schema and name", async () => {
    const catalog = await loadCatalog(`
      create schema "a.b";
      create schema a;
      create table "a.b".c (in_ab int);
      create table a."b.c" (in_a int);
    `);
    expect(
      [
        ["a.b", "c"],
        ["a", "b.c"],
        ["a", "b"],
      ].map(([schema = "", name = ""]) =>
        findTable(catalog, schema, name)?.columns.map((column) => column.name),
      ),
    ).toStrictEqual([["in_ab"], ["in_a"], undefined]);
  });
});
