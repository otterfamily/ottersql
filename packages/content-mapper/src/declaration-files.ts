import { basename, dirname, join } from "node:path";

import { lineAndColumn } from "@ottersql/sql/tooling";

import { openQuerySession } from "./session.ts";
import type { QuerySession } from "./session.ts";

export interface DeclarationFileProblem {
  readonly file: string;
  /** Both start at 1, as `lineAndColumn` counts them. */
  readonly line: number;
  readonly column: number;
  readonly message: string;
}

/** A query file's declarations, for tools that cannot run content mappers. */
export interface DeclarationFile {
  /** Where the declarations go: `queries.d.sql.ts` next to `queries.sql`. */
  readonly path: string;
  readonly text: string;
  /** Problems in the query file; its other queries are still declared. */
  readonly problems: readonly DeclarationFileProblem[];
}

const GENERATED = "// Generated by ottersql from ";

/**
 * The declarations of each query file: what the content mapper serves for it. TypeScript reads them
 * for `./queries.sql` imports when `allowArbitraryExtensions` is on. Rejects with a `SchemaError`
 * when Postgres rejects the schema.
 */
export async function declarationFiles(
  schema: string,
  queryFiles: readonly { readonly path: string; readonly content: string }[],
): Promise<DeclarationFile[]> {
  const session = await openQuerySession(schema, { cache: true });
  try {
    const files: DeclarationFile[] = [];
    for (const file of queryFiles) {
      files.push(await declarationFile(session, file.path, file.content));
    }
    return files;
  } finally {
    await session.close();
  }
}

async function declarationFile(
  session: QuerySession,
  path: string,
  content: string,
): Promise<DeclarationFile> {
  const rendered = await session.renderFile(content);
  return {
    path: declarationFileName(path),
    text: `${GENERATED}${basename(path)}. Do not edit.\n${rendered.text}`,
    problems: rendered.diagnostics.map(({ start, messageText }) => {
      const { line, column } = lineAndColumn(content, start);
      return { file: path, line, column, message: messageText };
    }),
  };
}

/** `queries.sql` → `queries.d.sql.ts`, the name TypeScript looks for with `allowArbitraryExtensions`. */
export function declarationFileName(queryFile: string): string {
  return join(dirname(queryFile), `${basename(queryFile, ".sql")}.d.sql.ts`);
}

/** Whether a declaration file was written by ottersql, so it may be replaced or removed. */
export function isGeneratedDeclarationFile(text: string): boolean {
  return text.startsWith(GENERATED);
}
