import { readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";

import { lineAndColumn } from "@ottersql/sql";

import { openQuerySession } from "./session.ts";
import type { QuerySession } from "./session.ts";

export interface DeclarationFileProblem {
  readonly file: string;
  /** Both start at 1, as `lineAndColumn` counts them. */
  readonly line: number;
  readonly column: number;
  readonly message: string;
}

/**
 * Writes `queries.d.sql.ts` next to each `queries.sql`: the same declarations the content mapper
 * serves, for tools that cannot run content mappers. TypeScript reads them for `./queries.sql`
 * imports when `allowArbitraryExtensions` is on. Rejects with a `SchemaError` when Postgres rejects
 * the schema; problems in query files are returned and their declarations still written.
 */
export async function writeDeclarationFiles(options: {
  readonly schemaPath: string;
  readonly queryFiles: readonly string[];
}): Promise<readonly DeclarationFileProblem[]> {
  const session = await openQuerySession(await readFile(options.schemaPath, "utf8"));
  try {
    const problems: DeclarationFileProblem[] = [];
    for (const file of options.queryFiles) {
      problems.push(...(await writeDeclarationFile(session, file)));
    }
    return problems;
  } finally {
    await session.close();
  }
}

async function writeDeclarationFile(
  session: QuerySession,
  file: string,
): Promise<DeclarationFileProblem[]> {
  const content = await readFile(file, "utf8");
  const rendered = await session.renderFile(content);
  const header = `// Generated by ottersql from ${basename(file)}. Do not edit.\n`;
  await writeFile(declarationFileName(file), header + rendered.text);
  return rendered.diagnostics.map(({ start, messageText }) => {
    const { line, column } = lineAndColumn(content, start);
    return { file, line, column, message: messageText };
  });
}

/** `queries.sql` → `queries.d.sql.ts`, the name TypeScript looks for with `allowArbitraryExtensions`. */
export function declarationFileName(queryFile: string): string {
  return join(dirname(queryFile), `${basename(queryFile, ".sql")}.d.sql.ts`);
}
